"""Unit tests for the synthetic exam generator."""

from __future__ import annotations

import pytest
from pydicom.uid import (
    CTImageStorage,
    MRImageStorage,
    ComputedRadiographyImageStorage,
    DigitalXRayImageStorageForPresentation,
    ExplicitVRLittleEndian,
    NuclearMedicineImageStorage,
    PositronEmissionTomographyImageStorage,
    SecondaryCaptureImageStorage,
    UltrasoundImageStorage,
)

from dicomstore.generator import (
    MODALITY_SPECS,
    build_plan,
    iter_instances,
    iter_series_instances,
)

SOP_CLASS_BY_KEY = {
    "CT": CTImageStorage,
    "MR": MRImageStorage,
    "CR": ComputedRadiographyImageStorage,
    "DX": DigitalXRayImageStorageForPresentation,
    "US": UltrasoundImageStorage,
    "PT": PositronEmissionTomographyImageStorage,
    "NM": NuclearMedicineImageStorage,
    "SC": SecondaryCaptureImageStorage,
}


@pytest.mark.parametrize("key", sorted(MODALITY_SPECS))
def test_modality_spec_sop_class(key):
    assert MODALITY_SPECS[key].sop_class_uid == SOP_CLASS_BY_KEY[key]


@pytest.mark.parametrize("key", sorted(MODALITY_SPECS))
def test_single_instance_from_each_modality(key):
    plan = build_plan([key], 1, 1, patient_name="TEST^X", accession="ACC1")
    instances = list(iter_instances(plan))
    assert len(instances) == 1
    ds = instances[0]
    assert ds.Modality == key
    assert ds.SOPClassUID == SOP_CLASS_BY_KEY[key]
    assert ds.Rows == MODALITY_SPECS[key].rows
    assert ds.Columns == MODALITY_SPECS[key].cols
    assert ds.BitsAllocated == MODALITY_SPECS[key].bits
    samples = 1
    assert len(ds.PixelData) == ds.Rows * ds.Columns * samples * (ds.BitsAllocated // 8)
    assert ds.SamplesPerPixel == 1
    assert ds.PhotometricInterpretation == "MONOCHROME2"
    assert ds.file_meta.TransferSyntaxUID == ExplicitVRLittleEndian
    assert ds.file_meta.MediaStorageSOPClassUID == SOP_CLASS_BY_KEY[key]
    assert ds.file_meta.MediaStorageSOPInstanceUID == ds.SOPInstanceUID
    for tag in ("SOPInstanceUID", "StudyInstanceUID", "SeriesInstanceUID",
                "AccessionNumber", "PatientName", "PatientID", "StudyDate"):
        assert getattr(ds, tag), f"missing {tag}"


def test_overrides_applied():
    plan = build_plan(["CT"], 2, 3, patient_name="DOE^JANE", patient_id="PID42",
                      accession="ACC-42", study_description="My test",
                      study_date="20250101")
    assert plan.patient_name == "DOE^JANE"
    assert plan.patient_id == "PID42"
    assert plan.accession == "ACC-42"
    assert plan.study_description == "My test"
    assert plan.study_date == "20250101"
    instances = list(iter_instances(plan))
    assert len(instances) == 6
    assert all(ds.PatientName == "DOE^JANE" for ds in instances)
    assert all(ds.AccessionNumber == "ACC-42" for ds in instances)
    # Series numbered 1..2, instances numbered 1..3 within each series
    numbers = sorted({ds.SeriesNumber for ds in instances})
    assert numbers == [1, 2]
    s1 = [ds.InstanceNumber for ds in instances if ds.SeriesNumber == 1]
    assert sorted(s1) == [1, 2, 3]


def test_uids_unique():
    plan = build_plan(["CT", "MR"], 2, 10)
    uids = [ds.SOPInstanceUID for ds in iter_instances(plan)]
    assert len(uids) == len(set(uids))
    assert len({ds.SeriesInstanceUID for ds in iter_instances(plan)}) == 2


def test_modalities_cycle_across_series():
    plan = build_plan(["CT", "MR"], 5, 1)
    assert [s.modality for s in plan.series] == ["CT", "MR", "CT", "MR", "CT"]


def test_blank_accession_autogenerated():
    plan = build_plan(["CT"], 1, 1)
    assert plan.accession.startswith("SYN-")
    plan2 = build_plan(["CT"], 1, 1)
    assert plan.accession != plan2.accession


def test_blank_patient_name_autogenerated():
    plan = build_plan(["CT"], 1, 1)
    assert plan.patient_name.startswith("TEST^PATIENT")


def test_unknown_modality_rejected():
    with pytest.raises(ValueError, match="Unknown modality"):
        build_plan(["XX"], 1, 1)


def test_empty_modalities_rejected():
    with pytest.raises(ValueError, match="At least one modality"):
        build_plan([], 1, 1)


def test_iter_series_instances_is_subset():
    plan = build_plan(["CT", "MR"], 2, 4)
    first = list(iter_series_instances(plan, plan.series[0]))
    assert len(first) == 4
    assert all(ds.SeriesInstanceUID == plan.series[0].series_uid for ds in first)


def test_lazy_iteration():
    plan = build_plan(["CT"], 50, 100)
    gen = iter_instances(plan)
    first = next(gen)
    assert first.Modality == "CT"
    # Only one instance materialized so far; the rest are produced on demand.
    assert sum(1 for _ in gen) == plan.instance_count - 1
